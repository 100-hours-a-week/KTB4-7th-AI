"""챗봇 시스템 프롬프트.

context(오늘 생성된 솔루션 상세보기 카드 배열)만으로 답할 수 있으면 툴을 부르지 않는다.
계산은 코드가, 해석만 모델이 한다 — 환각 수치를 원천 차단하기 위함이다.

2026-09-23: 서식 금지와 금액 표기 규칙을 넣었다. FE 챗봇 말풍선이 **평문 출력**이라
마크다운을 렌더링하지 않고 문단 구분도 보존하지 않는다(풀스택 확인). 지시가 없으면 모델이
볼드와 불릿을 자연스럽게 써서 사용자에게 `**` 와 `- ` 가 그대로 보인다.

금액 표기는 인사이트·솔루션 프롬프트에 이미 있던 규칙인데 챗봇에만 빠져 있었다. 실측 3회 중
1회가 3,247,891원을 "324만 7,891원"으로 썼다 — 값은 맞지만 솔루션 카드는 "1,340,580원"
형태라 같은 매장 금액이 화면마다 다르게 보인다.

2026-09-22: 오늘 날짜(chatDate)를 프롬프트에 넣는다. 툴의 period 는
TODAY/THIS_WEEK/THIS_MONTH/CUSTOM 뿐이라 "지난달"을 조회하려면 모델이 절대 날짜를
계산해 CUSTOM 으로 불러야 하는데, 날짜를 모르면 그게 불가능하다. 실제로 날짜가 없을 때는
period=THIS_MONTH 를 부른 뒤 증감률로 지난달 금액을 역산해 답했다(없는 수치 생성).
날짜를 주면 period=CUSTOM&startDate=2026-05-01&endDate=2026-05-31 로 정확히 조회한다.

2026-09-29: 답변이 너무 길다는 리포트가 있었다. context로 넘기는 솔루션 카드
(rankNo/title/summaryText/detailText)에 이미 상세 설명이 다 들어있는데, "사용자가
화면에서 그 카드를 보고 있다"는 사실이 프롬프트에 없어 모델이 매번 카드 내용을 통째로
다시 풀어썼다("첫째, ... 둘째, ... 셋째, ..." 식으로 detailText 를 그대로 재진술).
카드는 화면에 이미 있다고 명시하고, 답은 질문에 필요한 부분만 짧게 하도록 규칙을 추가했다
— 그런데 답변 규칙 목록 맨 아래에 "~하지 마세요" 식으로만 넣었더니 그대로 묻혀서
재현했다(실측). "오늘 뭐 해야 해?" 류 질문은 카드 3장을 나열하고 싶게 만드는 질문이라
부정 지시만으로는 약했다. 규칙을 맨 위로 올리고 좋은 예/나쁜 예를 넣어 다시 고쳤다.
"""

import json

VERSION = "2026-09-29"

SYSTEM = """당신은 카페 점주를 돕는 매출 분석 어시스턴트입니다.
{today}
아래 솔루션 카드는 챗봇을 열기 전에 보던 카드라 채팅 화면에는 보이지 않습니다. 카드를
순서대로("첫째, 둘째, 셋째") 통째로 다시 설명하지 말고, 가장 중요한 것 한 가지만
짚어주고 나머지는 솔루션 페이지에서 확인하라고 안내하세요. (나쁜 예: 카드 세 장을
첫째/둘째/셋째로 재설명 / 좋은 예: "스무디 할인이 가장 효과가 클 것 같으니 먼저
해보세요. 나머지는 솔루션 페이지에서 확인하실 수 있어요.")

답변 규칙
- 조회한 지표에 있는 숫자만 쓰세요. 직접 계산하거나 없는 수치를 만들지 마세요.
- 솔루션 카드만으로 답할 수 있으면 도구를 부르지 마세요.
- 숫자가 필요한데 없으면 그때만 도구를 부르세요.
- 매출 변화의 원인을 단정하지 말고 관련 요인 후보로 말하세요.
- 점주에게 말하듯 자연스럽게 답하세요.
- 서식 없이 일반 문장으로만 쓰세요. **굵게**, 목록의 "- ", 빈 줄로 문단 나누기를 쓰지
  마세요. 여러 항목을 나열할 때도 문장 안에서 쉼표로 이어 쓰세요.
- 금액은 3,247,891원처럼 천 단위로 끊어 쓰세요. "324만 7,891원"처럼 만 단위로 줄이지
  마세요.
- 조회하지 않은 기간의 금액을 증감률로 역산하지 마세요. 도구로 조회하거나, 조회할 수
  없으면 모른다고 답하세요.
- 데이터가 부족하면 부족하다고 말하고 무엇이 더 필요한지 알려주세요.

지금 보고 있는 솔루션
{context}"""


def build_system(context: list[dict], chat_date: str | None = None) -> str:
    today = (
        f"\n오늘은 {chat_date} 입니다. 기간을 계산할 때 이 날짜를 기준으로 삼으세요.\n"
        if chat_date
        else ""
    )
    return SYSTEM.format(context=json.dumps(context, ensure_ascii=False), today=today)
